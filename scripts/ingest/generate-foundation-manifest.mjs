#!/usr/bin/env node
// Regenerates the GENERATED review artefacts of the catalog check (rounds 10, 14):
//
//   * src/ingest/db/migrations/<NNNN>_<name>.manifest.json — the expected
//     foundation snapshot after migration NNNN, for 0001 and for every later
//     migration that changes the reviewed foundation (it ships its own manifest;
//     name the version on the command line the first time);
//   * src/ingest/db/systemPublicBaseline.ts — PUBLIC's explicit ACL entries in
//     pg_catalog / information_schema / pg_toast of a fresh database with 0001
//     applied, and the PostgreSQL MAJOR version it was taken on.
//
//   npm run worker:build
//   RATIO_TEST_DATABASE_URL=postgres://postgres@127.0.0.1:55432/postgres \
//     node scripts/ingest/generate-foundation-manifest.mjs [NNNN ...]
//
// Run it when a migration that changes the foundation is added or changed, or
// when moving to another PostgreSQL major version; then review the diff. The
// migrations are applied directly (not through the runner, whose check compares
// against what is being regenerated) in scratch databases that are dropped.
// DB tests assert that fresh databases still equal these files.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import process from 'node:process';
import { createRequire } from 'node:module';
import { URL, fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const require = createRequire(import.meta.url);
const { Client } = require(path.join(root, 'node_modules', 'pg'));
const { foundationSnapshot } = require(path.join(root, 'dist-worker', 'ingest', 'db', 'privilegeModel.js'));
const { systemPublicSnapshot, serverMajor } = require(path.join(root, 'dist-worker', 'ingest', 'db', 'systemBaseline.js'));
const migrationsDir = path.join(root, 'src', 'ingest', 'db', 'migrations');

async function withScratch(admin, fn) {
  const name = `ratio_manifest_${crypto.randomBytes(6).toString('hex')}`;
  const a = new Client({ connectionString: admin });
  await a.connect();
  await a.query(`CREATE DATABASE "${name}"`);
  try {
    const u = new URL(admin);
    u.pathname = `/${name}`;
    const c = new Client({ connectionString: u.toString() });
    await c.connect();
    try {
      return await fn(c);
    } finally {
      await c.end();
    }
  } finally {
    await a.query(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`);
    await a.end();
  }
}

async function applyUpTo(c, version) {
  const ups = fs.readdirSync(migrationsDir).filter((f) => /^\d{4}_[a-z0-9_]+\.up\.sql$/.test(f) && f.slice(0, 4) <= version).sort();
  if (!ups.some((f) => f.startsWith(version))) throw new Error(`no up migration for version ${version}`);
  for (const f of ups) {
    await c.query('BEGIN');
    await c.query(fs.readFileSync(path.join(migrationsDir, f), 'utf8'));
    await c.query('COMMIT');
    await c.query('RESET ROLE');
  }
  return ups.find((f) => f.startsWith(version));
}

async function main() {
  const admin = process.env.RATIO_TEST_DATABASE_URL;
  if (!admin) throw new Error('RATIO_TEST_DATABASE_URL (a superuser URL) is required');
  const existing = fs.readdirSync(migrationsDir).filter((f) => f.endsWith('.manifest.json')).map((f) => f.slice(0, 4));
  const versions = [...new Set(['0001', ...existing, ...process.argv.slice(2)])].sort();
  for (const version of versions) {
    await withScratch(admin, async (c) => {
      const up = await applyUpTo(c, version);
      await c.query('BEGIN READ ONLY');
      const entries = await foundationSnapshot(c);
      if (version === '0001') {
        const sys = await systemPublicSnapshot(c);
        const major = await serverMajor(c);
        const body =
          '// GENERATED by scripts/ingest/generate-foundation-manifest.mjs from a fresh database with 0001\n' +
          `// applied on PostgreSQL ${major}. Do not edit by hand: regenerate and review the diff.\n` +
          '// privileges.db.test.ts fails if a fresh database no longer equals this list.\n' +
          `export const SYSTEM_PUBLIC_BASELINE_DATA = {\n  pgMajor: ${major},\n  entries: [\n` +
          sys.map((e) => `    ${JSON.stringify(e)},`).join('\n') +
          '\n  ] as readonly string[],\n};\n';
        fs.writeFileSync(path.join(root, 'src', 'ingest', 'db', 'systemPublicBaseline.ts'), body);
        process.stdout.write(`wrote system baseline: ${sys.length} entries (PostgreSQL ${major})\n`);
      }
      await c.query('ROLLBACK');
      const file = up.replace(/\.up\.sql$/, '.manifest.json');
      fs.writeFileSync(path.join(migrationsDir, file), JSON.stringify(entries, null, 2) + '\n');
      process.stdout.write(`wrote ${file}: ${entries.length} entries\n`);
    });
  }
}

main().catch((e) => {
  process.stderr.write(`${e.message}\n`);
  process.exitCode = 1;
});
