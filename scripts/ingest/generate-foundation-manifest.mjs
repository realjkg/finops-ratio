#!/usr/bin/env node
// Regenerates src/ingest/db/foundationManifest.ts from a FRESH apply of the
// shipped 0001 (round 10). Run only when 0001 (or a reviewed later migration
// that intentionally changes a 0001 object) changes, then review the diff:
//
//   npm run worker:build
//   RATIO_TEST_DATABASE_URL=postgres://postgres@127.0.0.1:55432/postgres \
//     node scripts/ingest/generate-foundation-manifest.mjs
//
// The 0001 SQL is executed directly (not through the runner, whose check would
// compare against the manifest being regenerated) in a scratch database that
// is dropped afterwards. foundation.db.test.ts asserts that a fresh apply
// equals the stored manifest, so the two cannot drift silently.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import process from 'node:process';
import { createRequire } from 'node:module';
import { URL, fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const require = createRequire(import.meta.url);
const { Client } = require(path.join(root, 'node_modules', 'pg'));
const { loadMigrations } = require(path.join(root, 'dist-worker', 'ingest', 'db', 'migrationFiles.js'));
const { foundationSnapshot } = require(path.join(root, 'dist-worker', 'ingest', 'db', 'privilegeModel.js'));

async function main() {
  const admin = process.env.RATIO_TEST_DATABASE_URL;
  if (!admin) throw new Error('RATIO_TEST_DATABASE_URL (a superuser URL) is required');
  const name = `ratio_manifest_${crypto.randomBytes(6).toString('hex')}`;
  const a = new Client({ connectionString: admin });
  await a.connect();
  await a.query(`CREATE DATABASE "${name}"`);
  try {
    const u = new URL(admin);
    u.pathname = `/${name}`;
    const c = new Client({ connectionString: u.toString() });
    await c.connect();
    try {
      const up = loadMigrations(path.join(root, 'src', 'ingest', 'db', 'migrations')).find((m) => m.version === '0001');
      await c.query('BEGIN');
      await c.query(up.upSql);
      await c.query('COMMIT');
      await c.query('RESET ROLE');
      await c.query('BEGIN READ ONLY');
      const entries = await foundationSnapshot(c);
      await c.query('ROLLBACK');
      const body =
        '// GENERATED by scripts/ingest/generate-foundation-manifest.mjs from a fresh apply of\n' +
        '// 0001_ratio_schema.up.sql (PostgreSQL 16). Do not edit by hand: regenerate and review the\n' +
        '// diff. foundation.db.test.ts fails if a fresh apply no longer equals this list.\n' +
        `// checksum of the 0001 up file at generation: ${up.checksum}\n` +
        'export const FOUNDATION_0001: readonly string[] = [\n' +
        entries.map((e) => `  ${JSON.stringify(e)},`).join('\n') +
        '\n];\n';
      fs.writeFileSync(path.join(root, 'src', 'ingest', 'db', 'foundationManifest.ts'), body);
      process.stdout.write(`wrote ${entries.length} entries\n`);
    } finally {
      await c.end();
    }
  } finally {
    await a.query(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`);
    await a.end();
  }
}

main().catch((e) => {
  process.stderr.write(`${e.message}\n`);
  process.exitCode = 1;
});
